HEADER_TEMPLATE = """\
// pesos firmware - TFLite model data (extern declarations).
// AUTO-GENERATED by tools/convert_model.py - do not edit by hand.

#pragma once

#include <cstddef>

#ifdef __cplusplus
extern "C" {
#endif

extern const unsigned char tflite_model[];
extern const unsigned int tflite_model_len;

#ifdef __cplusplus
}
#endif
"""

SOURCE_HEADER = """\
// pesos firmware - TFLite model bytes.
// AUTO-GENERATED by tools/convert_model.py - do not edit by hand.
// Source: {src_name} ({size} bytes)

#include "model_data.h"

alignas(8) const unsigned char tflite_model[] = {{
"""

STUB_DISABLED = """\
// pesos firmware - weak model data fallback.
// A generated model_data.cpp provides strong symbols when present.

#include "model_data.h"

#if defined(__GNUC__)
#define MODEL_DATA_WEAK __attribute__((weak))
#else
#define MODEL_DATA_WEAK
#endif

extern "C" {
extern MODEL_DATA_WEAK const unsigned char tflite_model[] = { 0 };
extern MODEL_DATA_WEAK const unsigned int tflite_model_len = 0;
}
"""


def format_bytes(data: bytes, per_line: int = 12, indent: str = "    ") -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i : i + per_line]
        line = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"{indent}{line},")
    return "\n".join(lines)


def resolve_existing_path(candidates: tuple[Path, ...], label: str) -> Path:
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    joined = "\n".join(f"  - {candidate}" for candidate in candidates)
    raise FileNotFoundError(f"No {label} file found. Checked:\n{joined}")


def parse_size(value: str) -> int:
    return int(value.strip(), 0)


def get_app_partition_size(partitions_path: Path) -> int | None:
    if not partitions_path.is_file():
        return None

    with partitions_path.open(newline="", encoding="utf-8") as handle:
        rows = (
            row
            for row in handle
            if row.strip() and not row.lstrip().startswith("#")
        )
        reader = csv.reader(rows)
        for row in reader:
            if len(row) < 5:
                continue
            name = row[0].strip()
            ptype = row[1].strip()
            subtype = row[2].strip()
            if ptype == "app" and (subtype.startswith("ota_") or subtype == "factory" or name.startswith("app")):
                return parse_size(row[4])
    return None


def export_smaller_tflite(
    pt_model_path: Path,
    data_yaml_path: Path,
    out_tflite_path: Path,
    imgsz: int,
) -> Path:
    if not pt_model_path.is_file():
        raise FileNotFoundError(f"PT model not found: {pt_model_path}")
    if not data_yaml_path.is_file():
        raise FileNotFoundError(f"data.yaml not found: {data_yaml_path}")

    export_name = out_tflite_path.parent.name.removesuffix("_saved_model")
    project_dir = out_tflite_path.parent.parent
    expected_file = out_tflite_path.parent / f"{export_name}_int8.tflite"
    script = (
        "from pathlib import Path; "
        "from ultralytics import YOLO; "
        f"pt = Path(r'{pt_model_path}'); "
        f"data = Path(r'{data_yaml_path}'); "
        f"project = Path(r'{project_dir}'); "
        f"name = r'{export_name}'; "
        f"imgsz = {imgsz}; "
        "result = YOLO(str(pt)).export("
        "format='tflite', int8=True, imgsz=imgsz, data=str(data), "
        "project=str(project), name=name, exist_ok=True, verbose=True"
        "); "
        "print(result)"
    )
    subprocess.run([sys.executable, "-c", script], check=True)
    if expected_file.is_file():
        return expected_file

    fallback_candidates = (
        PESOLENS_DIR / "pesolens_best_saved_model" / "pesolens_best_int8.tflite",
        PESOLENS_ALT_DIR / "pesolens_best_saved_model" / "pesolens_best_int8.tflite",
    )
    for candidate in fallback_candidates:
        if candidate.is_file():
            return candidate

    raise FileNotFoundError(f"Expected exported TFLite file not found: {expected_file}")


def resolve_tflite_path(
    tflite_path: Path,
    partitions_path: Path,
    pt_model_path: Path,
    data_yaml_path: Path,
    export_imgsz: int,
) -> tuple[Path, int | None]:
    if not tflite_path.is_file():
        raise FileNotFoundError(f"tflite file not found: {tflite_path}")

    app_partition_size = get_app_partition_size(partitions_path)
    if app_partition_size is None:
        return tflite_path, None

    original_size = tflite_path.stat().st_size
    if original_size <= app_partition_size:
        return tflite_path, app_partition_size

    print(
        f"Input TFLite is {original_size:,} bytes, larger than the app partition "
        f"limit of {app_partition_size:,} bytes. Exporting imgsz={export_imgsz} fallback..."
    )
    smaller = export_smaller_tflite(pt_model_path, data_yaml_path, DEFAULT_SMALL_TFLITE, export_imgsz)
    smaller_size = smaller.stat().st_size
    if smaller_size > app_partition_size:
        print(
            f"WARNING: fallback export is still too large for flash: "
            f"{smaller_size:,} bytes > {app_partition_size:,} bytes. "
            f"Continuing with the smaller export so model_data files can still be generated."
        )
    return smaller, app_partition_size


def write_files(
    tflite_path: Path,
    header_path: Path,
    source_path: Path,
    partitions_path: Path,
    pt_model_path: Path,
    data_yaml_path: Path,
    export_imgsz: int,
) -> int:
    try:
        tflite_path, app_partition_size = resolve_tflite_path(
            tflite_path=tflite_path,
            partitions_path=partitions_path,
            pt_model_path=pt_model_path,
            data_yaml_path=data_yaml_path,
            export_imgsz=export_imgsz,
        )
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    data = tflite_path.read_bytes()
    size = len(data)
    if size == 0:
        print(f"ERROR: tflite file is empty: {tflite_path}", file=sys.stderr)
        return 3

    header_path.parent.mkdir(parents=True, exist_ok=True)
    source_path.parent.mkdir(parents=True, exist_ok=True)

    header_path.write_text(HEADER_TEMPLATE, encoding="utf-8")
    source_text = (
        SOURCE_HEADER.format(src_name=tflite_path.name, size=size)
        + format_bytes(data)
        + "\n};\n\n"
        + f"const unsigned int tflite_model_len = {size};\n"
    )
    source_path.write_text(source_text, encoding="utf-8")

    if STUB_SOURCE.exists() and STUB_SOURCE.resolve() != source_path.resolve():
        STUB_SOURCE.write_text(STUB_DISABLED, encoding="utf-8")

    written = source_path.read_text(encoding="utf-8")
    count = written.count("0x")
    ok = count == size

    print("model conversion summary")
    print(f"  source    : {tflite_path}")
    print(f"  header    : {header_path}")
    print(f"  cpp       : {source_path}")
    print(f"  size      : {size:,} bytes")
    if app_partition_size is not None:
        print(f"  app part  : {app_partition_size:,} bytes")
    print(f"  re-read   : {count:,} byte literals - {'OK' if ok else 'MISMATCH'}")
    if STUB_SOURCE.exists() and STUB_SOURCE.resolve() != source_path.resolve():
        print(f"  stub      : weak fallback refreshed ({STUB_SOURCE.name})")

    return 0 if ok else 4


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tflite", type=Path, default=DEFAULT_TFLITE)
    parser.add_argument("--out-header", type=Path, default=DEFAULT_HEADER)
    parser.add_argument("--out-source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--partitions", type=Path, default=DEFAULT_PARTITIONS)
    parser.add_argument("--pt-model", type=Path, default=DEFAULT_PT_MODEL)
    parser.add_argument("--data-yaml", type=Path, default=DEFAULT_DATA_YAML)
    parser.add_argument("--export-imgsz", type=int, default=DEFAULT_EXPORT_IMGSZ)
    args = parser.parse_args(argv)
    tflite_path = args.tflite if args.tflite.is_file() else resolve_existing_path(DEFAULT_TFLITE_CANDIDATES, "TFLite")
    pt_model_path = args.pt_model if args.pt_model.is_file() else resolve_existing_path(DEFAULT_PT_MODEL_CANDIDATES, "PyTorch model")
    data_yaml_path = args.data_yaml if args.data_yaml.is_file() else resolve_existing_path(DEFAULT_DATA_YAML_CANDIDATES, "data.yaml")
    return write_files(
        tflite_path=tflite_path,
        header_path=args.out_header,
        source_path=args.out_source,
        partitions_path=args.partitions,
        pt_model_path=pt_model_path,
        data_yaml_path=data_yaml_path,
        export_imgsz=args.export_imgsz,
    )


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
