#!/usr/bin/env python3
"""
pesos firmware — generate silent WAV placeholders for SPIFFS.

Why: the build pipeline uploads firmware/data/ as a SPIFFS image. If the audio
clips aren't recorded yet, we still need WAV files at the right paths so the
firmware can open them during dev. This emits 1-second silent 16 kHz mono
16-bit PCM WAVs for every clip ID the speech composer can emit.

Real audio clips will be generated by docs-specialist / audio-specialist using
edge-tts and dropped on top of these placeholders.
"""

import os
import sys
import wave
from pathlib import Path

# Match speech.cpp's clip vocabulary.
CLIP_IDS = [
    # digits 0..19
    "zero", "one", "two", "three", "four", "five", "six", "seven", "eight",
    "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen",
    "sixteen", "seventeen", "eighteen", "nineteen",
    # tens 20..90
    "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety",
    # multipliers
    "hundred", "thousand",
    # connectors / units / system
    "and", "peso", "pesos", "beep", "error",
]

SAMPLE_RATE = 16000
DURATION_SEC = 1.0
SAMPLE_WIDTH = 2  # 16-bit
NUM_CHANNELS = 1

def write_silent_wav(path: Path) -> None:
    n_samples = int(SAMPLE_RATE * DURATION_SEC)
    silence = bytes(SAMPLE_WIDTH * n_samples)
    with wave.open(str(path), "wb") as wf:
        wf.setnchannels(NUM_CHANNELS)
        wf.setsampwidth(SAMPLE_WIDTH)
        wf.setframerate(SAMPLE_RATE)
        wf.writeframes(silence)

def main() -> int:
    here = Path(__file__).resolve().parent
    data_dir = here.parent / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    written = 0
    skipped = 0
    for clip in CLIP_IDS:
        out = data_dir / f"{clip}.wav"
        if out.exists() and out.stat().st_size > 44:
            skipped += 1
            continue
        write_silent_wav(out)
        written += 1

    print(f"[make_placeholders] wrote {written} new clips, kept {skipped} existing")
    print(f"[make_placeholders] data dir: {data_dir}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
